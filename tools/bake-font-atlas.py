#!/usr/bin/env python3
"""Bake a glyph atlas from the camera's own font for the on-screen overlay.

Input : the TrueType extracted from the firmware's .ltt container
        (analysis/fonts/myinghei_gb18030.ttf) plus the Chinese string table
        (analysis/uxc/str_zh.json) which bounds the character set the menu uses.
Output: analysis/payloads/font_atlas.h

Format produced (freestanding-friendly):
    struct ov_glyph { unsigned int cp; signed char x, y; unsigned char w, h, adv; unsigned int off; };
    static const unsigned char ov_glyph_bits[];   // 4-bit alpha, two pixels/byte
    static const struct ov_glyph ov_glyphs[];     // sorted by cp

The overlay draws UTF-8 text by looking each codepoint up and blending the
glyph into its RGBA4444 frame, so labels come from the real UI font instead of
a host font.

usage: bake-font-atlas.py [--size 26] [--bits 4] [--charset all|labels]
"""
import argparse
import json
import struct

from PIL import Image, ImageDraw, ImageFont

TTF = '/mnt/f/project/a7r3/analysis/fonts/myinghei_gb18030.ttf'
STR_ZH = '/mnt/f/project/a7r3/analysis/uxc/str_zh.json'
OUT = '/mnt/f/project/a7r3/analysis/payloads/font_atlas.h'

ASCII = ''.join(chr(c) for c in range(0x20, 0x7f))
PUNCT = '、。，：；！？「」『』（）《》【】·—…～％’“”'


def charset_from_table():
    t = json.load(open(STR_ZH, encoding='utf-8'))
    chars = set(ASCII) | set(PUNCT)
    for s in t.values():
        chars.update(s)
    return sorted(c for c in chars if c.strip() or c == ' ')


def bake(char, font, size):
    """Render one glyph, return (xoff, yoff, w, h, adv, alpha bytes)."""
    img = Image.new('L', (size * 2, size * 2), 0)
    d = ImageDraw.Draw(img)
    base = size + 4
    d.text((size // 2, base), char, font=font, fill=255, anchor='ls')
    bbox = img.getbbox()
    adv = int(round(font.getlength(char)))
    if not bbox:
        return 0, 0, 0, 0, adv, b''
    x0, y0, x1, y1 = bbox
    glyph = img.crop(bbox)
    return x0 - size // 2, y0 - base, x1 - x0, y1 - y0, adv, glyph.tobytes()


def pack4(data):
    out = bytearray()
    for i in range(0, len(data), 2):
        hi = data[i] >> 4
        lo = (data[i + 1] >> 4) if i + 1 < len(data) else 0
        out.append((hi << 4) | lo)
    return bytes(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--size', type=int, default=26)
    ap.add_argument('--bits', type=int, default=4, choices=(4, 8))
    args = ap.parse_args()

    font = ImageFont.truetype(TTF, args.size)
    ascent, descent = font.getmetrics()
    print('metrics: ascent=%d descent=%d' % (ascent, descent))
    chars = charset_from_table()
    print('charset: %d characters, font size %d, %d bits' %
          (len(chars), args.size, args.bits))

    glyphs = []
    blob = bytearray()
    for ch in chars:
        x, y, w, h, adv, alpha = bake(ch, font, args.size)
        if not alpha:
            # keep zero-size glyphs (space etc.) so their advance still applies
            glyphs.append((ord(ch), 0, 0, 0, 0, adv, len(blob)))
            continue
        if args.bits == 4:
            alpha = pack4(alpha)
        off = len(blob)
        blob.extend(alpha)
        glyphs.append((ord(ch), x, y, w, h, adv, off))
    glyphs.sort()
    print('glyphs: %d, bitmap %d bytes (%.1f KiB), header ~%d bytes'
          % (len(glyphs), len(blob), len(blob) / 1024.0, len(glyphs) * 16))

    with open(OUT, 'w') as f:
        f.write('/* generated by bake-font-atlas.py -- do not edit */\n')
        f.write('/* font: MYingHeiC-GB18030-SJ (firmware), %d px, %d-bit alpha */\n'
                % (args.size, args.bits))
        f.write('#ifndef OV_FONT_ATLAS_H\n#define OV_FONT_ATLAS_H\n')
        f.write('struct ov_glyph { unsigned int cp; signed char x, y;'
                ' unsigned char w, h, adv; unsigned int off; };\n')
        f.write('#define OV_FONT_PX %d\n#define OV_FONT_BITS %d\n'
                % (args.size, args.bits))
        f.write('#define OV_FONT_ASCENT %d\n#define OV_FONT_DESCENT %d\n'
                % (ascent, descent))
        f.write('static const unsigned char ov_glyph_bits[%d] = {\n'
                % max(1, len(blob)))
        for i in range(0, len(blob), 24):
            f.write('  ' + ','.join(str(b) for b in blob[i:i + 24]) + ',\n')
        f.write('};\n')
        f.write('static const struct ov_glyph ov_glyphs[%d] = {\n' % len(glyphs))
        for cp, x, y, w, h, adv, off in glyphs:
            f.write('  {0x%04x,%d,%d,%d,%d,%d,%d},\n' % (cp, x, y, w, h, adv, off))
        f.write('};\n')
        f.write('#define OV_GLYPH_COUNT %d\n' % len(glyphs))
        f.write('#endif\n')
    print('wrote %s' % OUT)
    return 0


if __name__ == '__main__':
    import sys
    sys.exit(main())
