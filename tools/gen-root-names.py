#!/usr/bin/env python3
"""Generate probe_menu_roots.h: every exported cmnViewSettingNodeRoot* name.

The probe cannot enumerate dynsym at runtime (no symbol-table scanning from a
preload lib without parsing the ELF), so the candidate list is baked in at build
time from our own /usr dump.  Only CautionConfig.so definitions are kept.
"""
import io
import os
import sys

sys.path.insert(0, "/mnt/f/project/a7r3/analysis")
from ext2_locate import Ext2, DUMPS  # noqa: E402

from elftools.elf.elffile import ELFFile  # noqa: E402

OUT = "/mnt/f/project/a7r3/analysis/payloads/probe_menu_roots.h"


def main():
    fs = Ext2(os.path.join(DUMPS, "nflasha15.bin"))
    paths = {p.lstrip("/"): ino for ino, p in fs.walk().items()}
    data = fs.read_file(paths["lib/CautionConfig.so"])
    elf = ELFFile(io.BytesIO(data))
    names = []
    for sym in elf.get_section_by_name(".dynsym").iter_symbols():
        if not sym.name.startswith("cmnViewSettingNodeRoot"):
            continue
        if sym["st_shndx"] in ("SHN_UNDEF", 0, None):
            continue
        if sym["st_info"]["type"] != "STT_OBJECT":
            continue
        names.append(sym.name)
    names.sort()
    with open(OUT, "w") as f:
        f.write("/* generated by gen-root-names.py -- do not edit */\n")
        f.write("#define PM_ROOT_COUNT %d\n" % len(names))
        f.write("static const char *const g_all_roots[PM_ROOT_COUNT] = {\n")
        for n in names:
            f.write('    "%s",\n' % n)
        f.write("};\n")
    print("wrote %s: %d roots" % (OUT, len(names)))


if __name__ == "__main__":
    main()
